import results from "../../../../../benchmarks/results.json";

import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";

const SCENARIOS = [
  { key: "cold", label: "First analysis" },
  { key: "warm", label: "Same commit again" },
  { key: "new_commits", label: "New commits, with caches" },
  { key: "full_reindex", label: "Same commits, no caches" },
  { key: "graph", label: "Read the graph" },
  { key: "impact", label: "Rank impact" },
  { key: "backtest", label: "Backtest, up to 50 cases" },
] as const;

interface Timing {
  median_seconds: number;
  min_seconds: number;
  max_seconds: number;
  peak_rss_mib: number;
}

const seconds = (value: number) => `${value.toFixed(value < 1 ? 3 : 2)}s`;

function Subject({ subject }: { subject: (typeof results.subjects)[number] }) {
  const generated = subject.license === "generated";
  const timings = subject.results as unknown as Record<string, Timing | undefined>;
  return (
    <Card>
      <CardHeader>
        <CardTitle>{subject.name}</CardTitle>
        <span className="text-xs text-muted-foreground">
          {generated ? "Generated by CodeAtlas" : `Public project, ${subject.license}`}
        </span>
      </CardHeader>
      <CardContent>
        <p className="mb-3 font-mono text-xs text-muted-foreground">
          {subject.commit.slice(0, 10)} · {subject.first_parent_commits.toLocaleString("en-US")} commits ·{" "}
          {subject.ts_files.toLocaleString("en-US")} TS files · new-commit tasks add {subject.results.new_commit_count} commits
        </p>
        <table className="w-full text-sm">
          <thead>
            <tr className="text-left text-xs text-muted-foreground">
              <th scope="col" className="pb-1 font-normal">Task</th>
              <th scope="col" className="pb-1 text-right font-normal">Median</th>
              <th scope="col" className="pb-1 text-right font-normal">Range</th>
              <th scope="col" className="pb-1 text-right font-normal">Peak memory</th>
            </tr>
          </thead>
          <tbody>
            {SCENARIOS.map(({ key, label }) => {
              const timing = timings[key];
              if (!timing) return null;
              return (
                <tr key={key} className="border-t">
                  <th scope="row" className="py-1 text-left font-normal">{label}</th>
                  <td className="py-1 text-right font-mono text-xs">{seconds(timing.median_seconds)}</td>
                  <td className="py-1 text-right font-mono text-xs text-muted-foreground">
                    {seconds(timing.min_seconds)} to {seconds(timing.max_seconds)}
                  </td>
                  <td className="py-1 text-right font-mono text-xs">{timing.peak_rss_mib} MiB</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </CardContent>
    </Card>
  );
}

/** Figures recorded by `benchmarks/run.py`, not from this machine or repository. */
export function BenchmarksPage() {
  return (
    <div className="mx-auto max-w-6xl space-y-4">
      <div>
        <h1 className="text-2xl font-semibold tracking-tight">Benchmarks</h1>
        <p className="mt-1 text-sm text-muted-foreground">
          Recorded by <code className="font-mono">make bench</code>, not measured live. Machine: {results.machine.cpu},{" "}
          {results.machine.memory_gib} GiB, {results.machine.os}. {results.tool}, {results.repetitions} repetitions of
          each task. Each analysis reads the newest 500 commits at most, however long the history is. The overview from
          cached data matched a full reindex on every run. These figures measure speed, not ranking quality.
        </p>
      </div>
      {results.subjects.map((subject) => (
        <Subject key={subject.name} subject={subject} />
      ))}
    </div>
  );
}
